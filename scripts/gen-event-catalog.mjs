/**
 * Generator for src/lib/api-auth/event-catalog.ts — the runtime list of every bus
 * event (the EventMap is a TYPE, so it has no runtime form on its own). Powers the
 * admin « Évènements » tab + the decoupling docs. Severity is NOT baked in — the
 * UI computes it live via severityFor(name) (pure). Completeness is enforced by
 * event-catalog.test.ts which re-parses events/types.ts and compares.
 *
 * Run:  node scripts/gen-event-catalog.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const SRC = "src/events/types.ts";
const OUT = "src/lib/api-auth/event-catalog.ts";

const src = readFileSync(SRC, "utf8");
// EventMap keys look like:  "domain.action": {   (one per line, dotted, lowercase)
const KEY_RE = /^\s*"([a-z][a-z0-9_]*(?:\.[a-z0-9_]+)+)":/gm;
const names = [...src.matchAll(KEY_RE)].map((m) => m[1]);
const unique = [...new Set(names)].sort();
if (unique.length !== names.length) {
  console.error(`!! duplicate event keys in ${SRC}`);
}

