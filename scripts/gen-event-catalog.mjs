const byDomain = {};
for (const n of unique) {
  const domain = n.split(".")[0];
  (byDomain[domain] ||= []).push(n);
}
const domains = Object.keys(byDomain).sort();

const esc = (s) => s.replace(/"/g, '\\"');
let body = "";
for (const d of domains) {
  const label = DOMAIN_LABELS[d] || d;
  body += `  {\n    domain: "${esc(d)}",\n    label: "${esc(label)}",\n    events: [\n`;
  for (const n of byDomain[d]) body += `      "${esc(n)}",\n`;
  body += `    ],\n  },\n`;
}

const header = `/**
 * GENERATED by scripts/gen-event-catalog.mjs — do not edit by hand.
 * Runtime list of every bus event (src/events/types.ts EventMap is a TYPE, so it
 * has no runtime form on its own). Powers the admin « Évènements » tab + docs.
 * Severity is computed live via severityFor() (src/events/severity.ts) — not baked
 * in here. Completeness enforced by src/lib/db/tests/event-catalog.test.ts.
 * Regenerate after adding an event: \`node scripts/gen-event-catalog.mjs\`.
 *
 * Total events: ${unique.length} across ${domains.length} domains.
 */

export type EventCatalogDomain = {
  /** First dotted segment of the event name. */
  domain: string;
  label: string;
  events: string[];
};

export const EVENT_CATALOG: EventCatalogDomain[] = [
${body}];

/** Flat list of every catalogued event name (for the drift test + counts). */
export const EVENT_NAMES: string[] = EVENT_CATALOG.flatMap((d) => d.events);

export const EVENT_COUNT = EVENT_NAMES.length;
`;

writeFileSync(OUT, header, "utf8");
console.log(`wrote ${OUT}: ${unique.length} events across ${domains.length} domains`);
